// The one answer a run ever gives: the scenario it belonged to, when it ended, and whether the
// behaviour held. A run that stopped before its end state can only honestly say UNKNOWN.
inline BehaviourAction::Result::SharedPtr behaviour_result(
        const std::array<std::uint8_t, 16> &context_id,
        const rclcpp::Time &stamp,
        std::uint8_t trinary) {
    auto result = std::make_shared<BehaviourAction::Result>();
    result->result.scenario_context_id.uuid = context_id;
    result->result.stamp = stamp;
    result->result.trinary.value = trinary;
    return result;
}

